/* Generates supabase/seed.sql from src/data/*.json — the launch content for the database.
   Run: node scripts/build-seed-sql.js   then paste supabase/seed.sql into the Supabase SQL editor.
   Idempotent: towns/races/articles upsert; places are replaced per town. */
const fs = require("fs");
const path = require("path");
const D = (n) => JSON.parse(fs.readFileSync(path.join(__dirname, "../src/data", n + ".json"), "utf8"));

const towns = D("towns"), geo = D("town-geo"), when = D("town-when"), seedo = D("town-seedo"), races = D("races"),
  locked = D("rank-locked"), originals = D("originals");

const q = (v) => (v === undefined || v === null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => (v === undefined || v === null ? "null" : q(JSON.stringify(v)) + "::jsonb");
const arr = (a) => "array[" + (a || []).map(q).join(",") + "]::text[]";
const num = (v) => (v === undefined || v === null || v === "" ? "null" : Number(v));
const slugify = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

function discipline(p) {
  const s = `${p.n || ""} ${p.note || ""}`.toLowerCase();
  if (/rail trail|rail-trail|greenway|bikeway|cycleway|cycle path|bike path|sealed path|promenade|bike route/.test(s)) return "road";
  if (/gravel/.test(s)) return "gravel";
  if (/\bmtb\b|singletrack|single track|bike park|downhill|enduro|flow|trail/.test(s)) return "mtb";
  if (/climb|summit|\bhc\b| hill|gap|\bpass\b|\bcol\b|ascent|kom|switchback|peak/.test(s)) return "climbs";
  return "road";
}

let out = ["-- Cycletowns launch content (generated by scripts/build-seed-sql.js)", "begin;"];

// full-guide towns
for (const t of towns) {
  const g = geo[t.id] || {};
  out.push(`insert into towns (id,name,region,country,flag,currency,status,editorial_score,editorial_dims,photo,gallery,tags,personas,blurb,lat,lng,when_info,see_do)
values (${q(t.id)},${q(t.name)},${q(t.region)},${q(t.country)},${q(t.flag)},${q(t.cur || "$")},'full',${num(t.score)},${j(t.scoreDims)},${q(t.photo)},${arr(t.gallery)},${arr(t.tags)},${arr(t.personas)},${q(t.blurb)},${num(g.lat)},${num(g.lng)},${j(when[t.id])},${j(seedo[t.id])})
on conflict (id) do update set name=excluded.name,region=excluded.region,country=excluded.country,flag=excluded.flag,currency=excluded.currency,editorial_score=excluded.editorial_score,editorial_dims=excluded.editorial_dims,photo=excluded.photo,gallery=excluded.gallery,tags=excluded.tags,personas=excluded.personas,blurb=excluded.blurb,lat=excluded.lat,lng=excluded.lng,when_info=excluded.when_info,see_do=excluded.see_do,updated_at=now();`);
  out.push(`delete from places where town_id=${q(t.id)};`);
  const rows = [];
  (t.cafes || []).forEach((p, i) => rows.push(`(${q(t.id)},'cafe',${q(p.n)},${q(p.note)},${num(p.s)},false,null,null,${i})`));
  (t.shops || []).forEach((p, i) => rows.push(`(${q(t.id)},'shop',${q(p.n)},${q(p.note)},${num(p.s)},${!!p.hire},${num(p.price)},null,${i})`));
  (t.routes || []).forEach((p, i) => rows.push(`(${q(t.id)},'route',${q(p.n)},${q(p.note)},${num(p.s)},false,null,${q(discipline(p))},${i})`));
  (t.book || []).filter((b) => b.type === "Stay").forEach((b, i) => rows.push(`(${q(t.id)},'stay',${q(b.name)},'',null,false,${num(b.price)},null,${i})`));
  (seedo[t.id] || []).forEach((s, i) => rows.push(`(${q(t.id)},'thing',${q(s[1])},${q(s[0] + " " + s[2])},null,false,null,null,${i})`));
  if (rows.length) out.push(`insert into places (town_id,kind,name,note,editorial_rating,hire,price,discipline,sort) values\n${rows.join(",\n")};`);
  out.push(`delete from races where town_id=${q(t.id)};`);
  const rr = (races[t.id] || []).filter((r) => !r.illustrative).map((r, i) => `(${q(t.id)},${q(r.kind)},${q(r.badge || "🏁")},${q(r.name)},${q(r.series)},${num(r.km)},${num(r.vert)},${r.date ? q(r.date) : "null"},${q(r.status)},${q(r.disc)},${q(r.note)},${i})`);
  if (rr.length) out.push(`insert into races (town_id,kind,badge,name,series,km,vert,race_date,status,discipline,note,sort) values\n${rr.join(",\n")};`);
}

// radar towns (no guide yet)
const full = new Set(towns.map((t) => t.id));
for (const [name, region, country, flag] of locked) {
  const id = slugify(name);
  if (full.has(id)) continue;
  out.push(`insert into towns (id,name,region,country,flag,status) values (${q(id)},${q(name)},${q(region)},${q(country)},${q(flag)},'radar') on conflict (id) do nothing;`);
}

// articles (Cycletowns Originals)
for (const a of originals) {
  out.push(`insert into articles (slug,title,dek,body,kind,series,episode,town_id,image_kind,published,published_at)
values (${q(slugify(a.title))},${q(a.title)},${q(a.dek)},${q(a.body)},${q(a.kind)},${q(a.series)},${num(a.ep)},${a.town && full.has(a.town) ? q(a.town) : "null"},${q(a.img || "road")},true,now())
on conflict (slug) do update set title=excluded.title,dek=excluded.dek,body=excluded.body,kind=excluded.kind,series=excluded.series,episode=excluded.episode,town_id=excluded.town_id,image_kind=excluded.image_kind;`);
}
out.push("commit;");
fs.writeFileSync(path.join(__dirname, "../supabase/seed.sql"), out.join("\n\n") + "\n");
console.log("wrote supabase/seed.sql:", towns.length, "towns,", locked.length, "radar towns,", originals.length, "articles");
